/**
 * Generates public/images/placeholders/SHOT-LIST.md from the built pages.
 * Lists every image slot (path + shot description + pages that use it) and
 * whether the photo file already exists.
 *
 * Usage: npm run shots   (builds first, then writes the list)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(root, 'dist');
const publicDir = path.join(root, 'public');
const outFile = path.join(publicDir, 'images', 'placeholders', 'SHOT-LIST.md');

// <span class="media-ph" … data-slot-src="SRC"><span class="media-ph__label">…BRIEF</span>
const SLOT_RE = /data-slot-src="([^"]+)">\s*<span class="media-ph__label">(?:<i[^>]*><\/i>|<svg[\s\S]*?<\/svg>)?([^<]*)<\/span>/g;

const slots = new Map();
for (const file of fs.readdirSync(distDir).filter((f) => f.endsWith('.html') && f !== 'styleguide.html')) {
  const html = fs.readFileSync(path.join(distDir, file), 'utf8');
  for (const [, src, brief] of html.matchAll(SLOT_RE)) {
    const entry = slots.get(src) || { brief: brief.trim().replace(/&amp;/g, '&'), pages: new Set() };
    entry.pages.add(file.replace('.html', ''));
    slots.set(src, entry);
  }
}

const rows = [...slots.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([src, { brief, pages }]) => {
    const done = fs.existsSync(path.join(publicDir, src)) ? '✅' : '—';
    return `| ${done} | \`${src}\` | ${brief} | ${[...pages].join(', ')} |`;
  });

const supplied = rows.filter((r) => r.startsWith('| ✅')).length;

const md = `# Photography shot list

_Generated by \`npm run shots\` — do not edit by hand._

Save each photo at the exact path below (relative to \`public/\`). It replaces the
placeholder automatically; no code changes needed.

Style for all shots: premium studio or editorial lighting, dark/neutral backgrounds,
minimum 2000px on the long edge, JPG (~80% quality) or WebP. Hero images: keep the
lower-left area calm, as text sits there.

**${supplied} of ${rows.length} photos supplied.**

| Done | File | Shot | Used on |
|---|---|---|---|
${rows.join('\n')}

## Rules
- Real Hudaya Enterprises photography is preferred. If stock photos are used, log each one in \`CREDITS.md\`.
- Never caption stock photography as the company's own factory, team or products.
`;

fs.writeFileSync(outFile, md);
console.log(`SHOT-LIST.md written: ${rows.length} image slots (${supplied} supplied).`);
